import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const read=name=>readFileSync(new URL(name,root),'utf8');
const fox=read('freedom-chat-page.js');
const styles=read('freedom-chat-page.css');
const boot=read('boot.js');
const ai=read('freedom-ai.js');
const worker=read('cloudflare/elara-ai-worker.js');
const config=read('ai-gateway-config.js');
const original=read('freedom-dashboard-r2026.js');

assert.ok(existsSync(new URL('assets/ui/fox-loved.webp',root)),'Fox image must be bundled with the actual site');
assert.match(fox,/freedom-fox-chat-box/,'Fox preview must render on the Freedom dashboard');
assert.match(fox,/data-fox-open/,'Preview must be clickable');
assert.match(fox,/freedom-fox-overlay/,'Chat must expand into an overlay');
assert.match(fox,/aria-modal/,'Expanded chat should identify itself as a modal');
assert.match(fox,/data-fox-close/,'Full screen must have its own close control');
assert.match(fox,/history\.pushState/,'Opening chat must be browser-back compatible');
assert.match(fox,/history\.back\(\)/,'Closing chat must restore history');
assert.match(fox,/event\.key === 'Escape'/,'Escape must close the overlay');
assert.match(fox,/placeholder\.replaceWith\(card\)/,'The original live chat should be restored, not re-created');
assert.ok(!fox.includes('fetch('),'Fox UI must preserve existing admin configured AI transport, not use another endpoint');
assert.match(ai,/\.freedom-fox-overlay \[data-f-ai-host\]/,'Active original AI host must follow the card into overlay');
assert.match(ai,/ELARA_AI_API_URL/,'Existing secure Cloudflare AI URL must remain available');
assert.match(config,/elara-ai-gateway\./,'Do not remove existing configured gateway');
assert.match(boot,/freedom-chat-page\.js/,'The new chat script must be loaded');
assert.match(boot,/freedom-chat-page\.css/,'The new chat styles must be loaded');
assert.match(original,/freedom-ai-card/,'The original AI card must still be preserved');
assert.match(styles,/position:fixed/,'Full screen view must cover viewport');
assert.match(styles,/safe-area-inset/,'Fullscreen view must respect phone safe areas');
assert.match(styles,/prefers-reduced-motion/,'User must be able to disable expand animation');
assert.match(worker,/You are Elara Fox/,'Fox personality must be backed by server-side AI policy');
assert.match(worker,/pretending you are human/,'The AI personality must retain clear identity');
assert.ok(!/AIza[0-9A-Za-z_-]{20,}/.test(fox),'Do not embed model tokens in public chat');
console.log('PASS Freedom Fox: in-dashboard preview, fullscreen with back, existing AI gateway, mascot, friendly policy, and reduced motion.');
