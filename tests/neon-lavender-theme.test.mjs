function runtime(saved){
  const memory=new Map(Object.entries(saved||{}));
  const storage={getItem:key=>memory.get(key)??null,setItem:(key,value)=>memory.set(key,String(value))};
  const classes=new Set();
  const body={classList:{toggle:(name,active)=>{if(active)classes.add(name);else classes.delete(name)},add:name=>classes.add(name),remove:name=>classes.delete(name)},dataset:{}};
  const element={style:{setProperty(){}},dataset:{}};
  const hosts={ 'drawer-settings-theme-area':{id:'drawer-settings-theme-area',innerHTML:''}, 'drawer-settings-area':{id:'drawer-settings-area',innerHTML:''}};
  const doc={readyState:'loading',body,documentElement:element,addEventListener(){},querySelector(){return null},querySelectorAll(){return []},getElementById(id){return hosts[id]||null}};
  const events=[];
  const fakeWindow={dispatchEvent:e=>events.push(e),addEventListener(){},matchMedia:()=>({matches:false,addEventListener(){}}),ElaraIcons:{icon:()=>''}};
  const ctx={window:fakeWindow,document:doc,localStorage:storage,matchMedia:()=>({matches:false}),CustomEvent:class{constructor(type,opts){this.type=type;this.detail=opts?.detail}},Event:class{constructor(type){this.type=type}},CSS:{escape:x=>String(x)},NodeFilter:{SHOW_TEXT:4},crypto:{randomUUID:()=> 'test-id'},setTimeout:()=>0,console};
  vm.runInNewContext(design,ctx);
  vm.runInNewContext(drawer,ctx);
  return {body,classes,storage,window:fakeWindow,events,hosts};
}
let r=runtime({'elara_preferences_v2':JSON.stringify({mode:'dark',color:'violet'})});
r.window.ElaraApplyTheme();
r.window.ElaraDrawerTest.renderSettings();
const settingsMarkup=r.hosts['drawer-settings-area'].innerHTML;
const galleryMarkup=r.hosts['drawer-settings-theme-area'].innerHTML;
assert.match(settingsMarkup,/id="drawer-settings-theme-area"/);
assert.equal(galleryMarkup.indexOf('شب‌های بی‌انتها')<galleryMarkup.indexOf('کهکشان یاسی'),true,'Midnight must be first');
assert.equal((galleryMarkup.match(/<img\b/g)||[]).length,8,'Only the eight actual theme choices show artwork');
assert.equal((galleryMarkup.slice(galleryMarkup.indexOf('elara-mode-group')).match(/<img\b/g)||[]).length,0,'Mode and Style have no artwork');
assert.match(galleryMarkup,/data-drawer-mode="light"/);
assert.match(galleryMarkup,/data-drawer-style="minimal"/);
