  await page.waitForSelector('[data-l5-auto]');
  const prev=page.locator('#l3-review-scene [data-l3-prev]');
  assert.equal(await prev.isEnabled(),true,'previous-word should be clickable even with no history '+width);
  await prev.click();
  assert.match(await page.locator('[data-l5-feedback]').textContent(),/کلمهٔ قبلی|previous word/i,'previous word feedback '+width);
  const select=await page.locator('#flash-front').evaluate(e=>({user:getComputedStyle(e).userSelect,webkit:getComputedStyle(e).webkitUserSelect}));
  assert.equal(select.user,'none','text selection must be suppressed during drag '+width);
  await page.locator('[data-l5-auto]').click();
  assert.equal(await page.locator('[data-l5-auto]').getAttribute('aria-pressed'),'true','auto logging enabled '+width);
  assert.equal(await page.locator('[data-l3-focus]').getAttribute('aria-pressed'),'true','auto starts canonical timer '+width);
  await page.locator('#word-reveal').click();
  const before=await page.locator('#flash-front').textContent();
  const target=page.locator('#l3-review-scene [data-l3-drag-surface]');
  const box=await target.boundingBox(),frontBox=await page.locator('#flash-front').boundingBox();assert.ok(box&&frontBox);
  const startX=frontBox.x+frontBox.width*.5,startY=frontBox.y+frontBox.height*.5;
