import {chromium} from 'playwright';
import {mkdirSync} from 'node:fs';
const url=(process.env.ELARA_TEST_URL||'http://127.0.0.1:4173').replace(/\/$/,'');
const dir='browser-artifacts/leitner-l5';mkdirSync(dir,{recursive:true});
const auth="window.ElaraAccount={user:{uid:'l5-qa',email:'qa@example.invalid',emailVerified:true}};document.body.classList.remove('cloud-locked');document.body.classList.add('cloud-ready');window.dispatchEvent(new Event('elara:account-ready'));";
const social="window.ElaraSocial={me:{uid:'l5-qa',name:'QA'},friends:[],refresh:async()=>{}};";
