  const dashboardOverflow=await page.evaluate(()=>Math.max(0,document.documentElement.scrollWidth-document.documentElement.clientWidth));
  assert.ok(dashboardOverflow<=4,'dashboard horizontal overflow '+width+': '+dashboardOverflow);
  if([390,1440].includes(width))await page.screenshot({path:dir+'/dashboard-'+width+'.png',fullPage:true,animations:'disabled'});
