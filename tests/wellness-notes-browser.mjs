import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const base=process.env.ELARA_TEST_URL||'http://127.0.0.1:4173';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:390,height:844}});
const cloud="window.ElaraAccount={user:{uid:'wellness-qa'},profile:{name:'Wellness QA',username:'wellness_qa',xp:50,profilePublic:true}};document.body.classList.remove('cloud-locked');document.body.classList.add('cloud-ready');document.getElementById('cloud-layer')?.setAttribute('hidden','');window.dispatchEvent(new Event('elara:account-ready'));";
const social="window.__wellnessPublished=[];window.ElaraSocial={me:{uid:'wellness-qa',name:'Wellness QA'},friends:[],requests:[],activities:[],publishActivity:async(type,detail)=>{window.__wellnessPublished.push({type,detail});return true},refresh:async()=>{}};window.dispatchEvent(new Event('elara:social-updated'));";
await page.route('**/cloud.js*',r=>r.fulfill({status:200,contentType:'application/javascript',body:cloud}));
await page.route('**/elara-social.js*',r=>r.fulfill({status:200,contentType:'application/javascript',body:social}));
await page.goto(base+'/?wellness-notes='+Date.now()+'#home',{waitUntil:'domcontentloaded',timeout:30000});
await page.waitForFunction(()=>window.ElaraOpen&&window.ElaraFeatureHubs&&window.ElaraWellnessPopups&&!document.documentElement.hasAttribute('data-elara-booting'),{timeout:35000});
await page.evaluate(()=>window.ElaraOpen('wellness-exercise'));
await page.waitForSelector('#panel-wellness-exercise:not(.hidden) .wellness-plans');
await page.locator('#panel-wellness-exercise [data-wellness-plan-edit="workout"]').click();
let popup=page.locator('.elwp-dialog[role="dialog"]');
await popup.waitFor();
assert.equal(await popup.locator('[data-elwp-meta="name"]').count(),1);
await popup.locator('[data-elwp-meta="description"]').fill('سه روز تمرین قدرتی\nدو روز کشش');
await popup.locator('[data-elwp-day="جمعه"]').click();
await popup.locator('[data-elwp-tab="check"]').click();
await popup.locator('[data-elwp-new-check]').fill('آماده‌سازی تشک تمرین');
await popup.locator('[data-elwp-action="add-check"]').click();
await popup.locator('[data-elwp-save]').click();
await popup.waitFor({state:'hidden'});
await page.waitForFunction(()=>JSON.parse(localStorage.getItem('elara_private_wellness_v1_wellness-qa')||'{}').workoutPlanNote?.includes('تمرین قدرتی'));
let state=await page.evaluate(()=>JSON.parse(localStorage.getItem('elara_private_wellness_v1_wellness-qa')));
assert.ok(state.workoutPlanFolders?.some(f=>f.checks?.some(c=>c.text==='آماده‌سازی تشک تمرین')),'checklist persists');
assert.ok(state.workoutPlanMeta.days.includes('جمعه'),'selected day persists');
assert.match(await page.locator('#wellness-workout-plan').innerText(),/تمرین قدرتی/);
await page.locator('#panel-wellness-exercise [data-wellness-plan-edit="nutrition"]').click();
popup=page.locator('.elwp-dialog');
await popup.locator('[data-elwp-meta="description"]').fill('برنامه تغذیه متعادل هفتگی');
await popup.locator('[data-elwp-action="new-folder"]').click();
await popup.locator('[data-elwp-new-folder]').fill('خرید هفتگی');
await popup.locator('[data-elwp-action="confirm-folder"]').click();
await popup.locator('[data-elwp-folder-title]').fill('لیست خرید من');
await popup.locator('[data-elwp-save]').click();
await popup.waitFor({state:'hidden'});
state=await page.evaluate(()=>JSON.parse(localStorage.getItem('elara_private_wellness_v1_wellness-qa')));
assert.ok(state.nutritionPlanFolders.some(f=>f.title==='لیست خرید من'));
assert.equal(state.nutritionPlanMeta.style,'متعادل');
assert.equal((await page.evaluate(()=>window.__wellnessPublished.length)),0,'private wellness leaked to social feed');
await page.evaluate(()=>window.ElaraOpen('wellness-sleep'));
await page.waitForSelector('#panel-wellness-sleep:not(.hidden) #elwp-sleep-dashboard');
await page.locator('#elwp-sleep-dashboard [data-elwp-action="open-sleep"]').click();
popup=page.locator('.elwp-dialog.elwp-sleep');
await popup.waitFor();
await popup.locator('[data-elwp-sleep="bed"]').fill('23:15');
await popup.locator('[data-elwp-sleep="wake"]').fill('07:00');
assert.match(await popup.locator('[data-elwp-duration]').innerText(),/۷|7/);
await popup.locator('[data-elwp-choice="quality"][data-elwp-value="عالی"]').click();
await popup.locator('[data-elwp-sleep="note"]').fill('خواب منظم شبانه');
await popup.locator('[data-elwp-save]').click();
await popup.waitFor({state:'hidden'});
state=await page.evaluate(()=>JSON.parse(localStorage.getItem('elara_private_wellness_v1_wellness-qa')));
assert.equal(state.sleep.length,1);
assert.equal(state.sleep[0].quality,'عالی');
assert.equal(state.sleep[0].note,'خواب منظم شبانه');
assert.match(await page.locator('#elwp-sleep-dashboard').innerText(),/عالی/);
await page.locator('#elwp-sleep-dashboard [data-elwp-action="open-sleep"]').click();
await page.keyboard.press('Escape');
await page.locator('.elwp-dialog').waitFor({state:'hidden'});
assert.equal((await page.evaluate(()=>JSON.parse(localStorage.getItem('elara_private_wellness_v1_wellness-qa')).sleep.length)),1,'Escape must discard draft');
let m=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
assert.ok(m.scroll<=m.width+1,'390px horizontal overflow '+JSON.stringify(m));
await page.setViewportSize({width:1440,height:900});
await page.evaluate(()=>window.ElaraOpen('wellness-exercise'));
await page.locator('#panel-wellness-exercise [data-wellness-plan-edit="workout"]').click();
await page.locator('.elwp-dialog').waitFor();
m=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,dialog:document.querySelector('.elwp-dialog').getBoundingClientRect().toJSON()}));
assert.ok(m.scroll<=m.width+1,'1440px horizontal overflow '+JSON.stringify(m));
assert.ok(m.dialog.width>=700&&m.dialog.right<=m.width+1,'desktop popup geometry');
await page.locator('.elwp-cancel').click();
assert.equal((await page.evaluate(()=>window.__wellnessPublished.length)),0);
await browser.close();
console.log('WELLNESS_REFERENCE_PASS training nutrition checklist folder sleep duration moods privacy mobile desktop');
